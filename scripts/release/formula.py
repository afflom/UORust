"""Write the Homebrew formula for one release from that release's SHA256SUMS.

    python3 -I scripts/release/formula.py ROOT TAG SHA256SUMS > Formula/uorust.rb

Every platform block is one archive SHA256SUMS lists (the archives release.yml
builds): uorust-<arch>-<vendor>-<os>.tar.gz for macOS and Linux. The
description, homepage, repository and license are read from the manifests.
`brew tap afflom/uorust https://github.com/afflom/UORust` then
`brew install afflom/uorust/uorust` installs it.
"""
import re, sys, tomllib

root, tag, sums_path = sys.argv[1:4]
version = tag.removeprefix("v")
assert re.fullmatch(r"\d+\.\d+\.\d+([-+].*)?", version), f"not a release tag: {tag}"
workspace = tomllib.load(open(f"{root}/Cargo.toml", "rb"))["workspace"]["package"]
crate = tomllib.load(open(f"{root}/crates/uorust/Cargo.toml", "rb"))["package"]
name = crate["name"]
# Homebrew's desc is one short phrase: the description up to its first colon.
desc = crate["description"].split(":")[0].strip().rstrip(".")
licenses = [l.strip() for l in workspace["license"].split(" OR ")]
repository = workspace["repository"]

# "<hex>  <name>" or "<hex> *<name>" (binary mode).
sums = {}
for line in open(sums_path, encoding="utf-8"):
    digest, file = line.split(None, 1)
    sums[file.strip().lstrip("*")] = digest
OS = {"apple-darwin": "on_macos", "unknown-linux-gnu": "on_linux"}
ARCH = {"aarch64": "on_arm", "x86_64": "on_intel"}
blocks = {}
for file, digest in sorted(sums.items()):
    m = re.fullmatch(rf"{name}-(\w+?)-(.+)\.tar\.gz", file)
    if not m or m.group(2) not in OS:
        continue
    arch, os_ = m.groups()
    assert re.fullmatch(r"[0-9a-f]{64}", digest), f"{file}: not a SHA-256: {digest}"
    blocks.setdefault(OS[os_], []).append((ARCH[arch], file, digest))
assert blocks, f"{sums_path} lists no macOS or Linux archive"

cls = name[0].upper() + name[1:]
out = [
    f"# Generated by scripts/release/formula.py from the SHA256SUMS of {tag}; do not edit.",
    f"class {cls} < Formula",
    f'  desc "{desc}"',
    f'  homepage "{workspace["homepage"]}"',
    f'  version "{version}"',
    "  license any_of: [" + ", ".join(f'"{l}"' for l in licenses) + "]",
    "",
]
for os_block in sorted(blocks):
    out.append(f"  {os_block} do")
    for arch_block, file, digest in sorted(blocks[os_block]):
        out += [
            f"    {arch_block} do",
            f'      url "{repository}/releases/download/{tag}/{file}"',
            f'      sha256 "{digest}"',
            "    end",
        ]
    out.append("  end")
out += [
    "",
    "  def install",
    f'    bin.install "{name}"',
    "  end",
    "",
    "  test do",
    f'    assert_match version.to_s, shell_output("#{{bin}}/{name} --version")',
    "  end",
    "end",
]
print("\n".join(out))
