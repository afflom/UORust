#!/usr/bin/env bash
# Commit what a writer changed under the named paths and push it to main as
# github-actions[bot], then dispatch the named workflows on the new head.
#
#     scripts/ci/push.sh "<commit subject>" "<path> ..." [workflow.yml ...]
#
# A push made with the workflow token starts no `push` workflow, so the gate
# and the page are dispatched explicitly for the commit this makes. Nothing is
# pushed when nothing changed, or when main moved past the commit the writers
# ran on: the newer push carries its own run. The checkout keeps no
# credentials (persist-credentials: false); the token is passed to this one
# push as a header and to `gh` through GH_TOKEN.
#
# With REBASE=1, when main moved only in workflow files, the commit is rebased
# onto the new main and pushed; any other newer commit can change what the
# writers write, so its own run regenerates instead. With REBASE=any, for a
# commit that holds no writer's output (a release's version and cadence,
# whose generated files generate.yml rewrites on top), it is rebased over any
# newer commit. With REBASE=1 and INPUTS, the pathspecs of everything the
# writers read (a workflow's trigger paths), a newer commit that changes
# none of them cannot change what the writers wrote (generate's
# regeneration, another crate's register and its ledger file), and the
# commit is rebased over it too: else a writer slower than generate would
# never land. A newer commit to the same files conflicts, and nothing is
# pushed. A rebase that conflicts pushes
# nothing. Inputs that moved underneath are regenerated by the next run, which
# the workflow's non-cancelling concurrency group queues behind this one.
set -euo pipefail
subject=$1
read -r -a paths <<<"$2"
shift 2
: "${GH_TOKEN:?GH_TOKEN is required}"
base=$(git rev-parse HEAD)
git add -- "${paths[@]}"
if git diff --cached --quiet; then
  echo "push: nothing changed under ${paths[*]}"
  exit 0
fi
git diff --cached --stat
git -c user.name='github-actions[bot]' \
  -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
  commit -q -m "$subject" -m "Written by the ${GITHUB_WORKFLOW:-local} workflow from ${base}."
auth=$(printf 'x-access-token:%s' "$GH_TOKEN" | base64 -w0)
remote="https://github.com/${GITHUB_REPOSITORY:?}.git"
head=$(git -c "http.extraheader=AUTHORIZATION: basic $auth" ls-remote "$remote" refs/heads/main | cut -f1)
if [[ ${REBASE:-0} != 1 && ${REBASE:-0} != any ]]; then
  if [[ $head != "$base" ]]; then
    echo "push: main moved from $base to $head; its own run regenerates"
    exit 0
  fi
  if ! git -c "http.extraheader=AUTHORIZATION: basic $auth" push "$remote" HEAD:refs/heads/main; then
    echo "push: main moved while pushing; its own run regenerates"
    exit 0
  fi
else
  for attempt in 1 2 3 4 5; do
    if [[ $head != "$base" ]]; then
      git -c "http.extraheader=AUTHORIZATION: basic $auth" fetch -q "$remote" "+refs/heads/main:refs/remotes/upstream/main"
      # A newer commit that changed anything but workflow files may change
      # what the writers write, and a commit of outputs rebased over it would
      # put stale outputs on main (bootstrap then fails "not this workspace's
      # register"). Only workflow-only commits are rebased over; otherwise the
      # newer push's own run regenerates.
      if [[ -n ${INPUTS:-} ]]; then
        read -r -a inputs <<<"$INPUTS"
        moved=$(git diff --name-only "$base" upstream/main -- "${inputs[@]}")
      else
        moved=$(git diff --name-only "$base" upstream/main -- . ':(exclude).github/workflows')
      fi
      if [[ ${REBASE} != any && -n $moved ]]; then
        echo "push: main moved from $base past more than workflow files; its own run regenerates"
        exit 0
      fi
      if ! git -c user.name='github-actions[bot]' -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
        rebase -q upstream/main; then
        git rebase --abort
        echo "push: the rebase onto main conflicts; nothing pushed"
        exit 0
      fi
      echo "push: main moved from $base; rebased onto $(git rev-parse upstream/main)"
      base=$(git rev-parse upstream/main)
    fi
    if git -c "http.extraheader=AUTHORIZATION: basic $auth" push "$remote" HEAD:refs/heads/main; then
      break
    fi
    if [[ $attempt == 5 ]]; then
      echo "push: main kept moving; nothing pushed"
      exit 0
    fi
    head=$(git -c "http.extraheader=AUTHORIZATION: basic $auth" ls-remote "$remote" refs/heads/main | cut -f1)
  done
fi
for workflow in "$@"; do
  gh workflow run "$workflow" --repo "$GITHUB_REPOSITORY" --ref main
  # A gate dispatched with the workflow token starts no workflow_run, so
  # gated.yml follows it and starts the release workflows on green.
  if [[ $workflow == bootstrap.yml ]]; then
    gh workflow run gated.yml --repo "$GITHUB_REPOSITORY" --ref main -f sha="$(git rev-parse HEAD)"
  fi
done
{
  echo "## $subject"
  echo
  echo "Pushed \`$(git rev-parse HEAD)\` to main and dispatched: $*"
} >>"${GITHUB_STEP_SUMMARY:-/dev/null}"
